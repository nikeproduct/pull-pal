#!/usr/bin/env bun
/**
 * Build every distributable artifact.
 *
 * Runs anywhere Bun does, including Windows — there is no second shell-script
 * build path to drift out of sync (v0.1 had one, and it was the only path that
 * could produce release artifacts while also being the one that forgot to
 * embed the version).
 *
 * Outputs:
 *   dist/                     standalone binaries, one per platform
 *   dist/SHA256SUMS           checksums for every release asset
 *   npm-packages/<plat>/      platform npm packages, binary in place
 */

import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { PLATFORMS } from "./platforms";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DIST = join(ROOT, "dist");
const SRC = join(ROOT, "src", "index.ts");

/** What each platform build produces, from the shared list in scripts/platforms.ts. */
const TARGETS = PLATFORMS.map((p) => ({
  /** bun --target value */
  target: p.bunTarget,
  /** Output filename in dist/ */
  out: p.asset,
  /** npm-packages/ subdirectory */
  pkgDir: p.key,
  /** Name the binary takes inside the npm package */
  pkgBin: p.bin,
}));

function run(cmd: string[], cwd = ROOT): { ok: boolean; stderr: string } {
  const r = Bun.spawnSync(cmd, { cwd, stdout: "pipe", stderr: "pipe" });
  return { ok: r.exitCode === 0, stderr: new TextDecoder().decode(r.stderr) };
}

function fail(message: string): never {
  console.error(`\nBuild failed: ${message}`);
  process.exit(1);
}

// ── Version embedding ──────────────────────────────────────────────────────
// Generated here *and* verified by `check-version` in CI, so a release can never
// ship a binary that reports the wrong version.
const pkg = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8")) as { version: string };
writeFileSync(
  join(ROOT, "src", "version.ts"),
  `// AUTO-GENERATED by scripts/build.ts — do not edit.\nexport const VERSION = ${JSON.stringify(pkg.version)};\n`,
  "utf8",
);
console.log(`Building pull-pal ${pkg.version}\n`);

mkdirSync(DIST, { recursive: true });
for (const t of TARGETS) mkdirSync(join(ROOT, "npm-packages", t.pkgDir), { recursive: true });

// ── Compile ────────────────────────────────────────────────────────────────
for (const t of TARGETS) {
  process.stdout.write(`  ${t.target.padEnd(20)}`);
  const result = run([
    "bun",
    "build",
    "--compile",
    `--target=${t.target}`,
    SRC,
    "--outfile",
    join(DIST, t.out),
  ]);
  if (!result.ok) fail(`could not compile ${t.target}\n${result.stderr}`);
  console.log("ok");
}

// ── npm platform packages ──────────────────────────────────────────────────
console.log("\nnpm packages:");
for (const t of TARGETS) {
  const dest = join(ROOT, "npm-packages", t.pkgDir, t.pkgBin);
  cpSync(join(DIST, t.out), dest);
  console.log(`  npm-packages/${t.pkgDir}/${t.pkgBin}`);
}

// ── Checksums ──────────────────────────────────────────────────────────────
//
// Published with every GitHub release, so anyone downloading a binary directly
// can verify it.
console.log("\nSHA256SUMS:");
const assets = TARGETS.map((t) => ({ path: join(DIST, t.out), name: t.out })).filter((a) =>
  existsSync(a.path),
);

const lines: string[] = [];
for (const asset of assets) {
  const hasher = new Bun.CryptoHasher("sha256");
  hasher.update(await Bun.file(asset.path).bytes());
  const digest = hasher.digest("hex");
  lines.push(`${digest}  ${asset.name}`);
  console.log(`  ${digest}  ${asset.name}`);
}
const sumsPath = join(DIST, "SHA256SUMS");
writeFileSync(sumsPath, `${lines.join("\n")}\n`, "utf8");

console.log(`
Done.
  binaries      ${DIST}
  checksums     ${sumsPath}
  npm packages  ${join(ROOT, "npm-packages")}
`);
